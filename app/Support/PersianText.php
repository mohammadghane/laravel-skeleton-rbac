<?php

namespace App\Support;

/**
 * یکسان‌سازی متن فارسی - تنها مرجع این تبدیل‌ها در کل پروژه.
 *
 * چرا لازم است؟ داده از سه مسیر وارد سیستم می‌شود (فرم‌های پنل، فایل اکسل، وب‌سرویس
 * پرسنلی) و هرکدام ممکن است شکل متفاوتی از یک حرف یا رقم بفرستند:
 *
 *   - «ي» و «ك» عربی در برابر «ی» و «ک» فارسی (کیبورد عربی/ویندوز قدیمی)
 *   - ارقام فارسی «۰۹»، عربی-هندی «٠٩» و لاتین «09»
 *
 * بدون یکسان‌سازی، «یحیی» تایپ‌شده با کیبورد فارسی هرگز رکورد «يحيي» آمده از وب‌سرویس
 * را پیدا نمی‌کند - هرچند برای کاربر دقیقاً یک کلمه‌اند. همین برای جست‌وجوی کد پرسنلی با
 * ارقام فارسی هم صادق است.
 */
class PersianText
{
    /** حروف عربی => معادل فارسی. */
    private const LETTERS = [
        'ي' => 'ی',   // YEH عربی
        'ى' => 'ی',   // ALEF MAKSURA
        'ك' => 'ک',   // KAF عربی
        'ﻙ' => 'ک',
        'ﻚ' => 'ک',
        'ة' => 'ه',   // TEH MARBUTA
        'ۀ' => 'ه',
        'أ' => 'ا',
        'إ' => 'ا',
        'آ' => 'آ',
        'ؤ' => 'و',
        'ئ' => 'ی',
    ];

    /** ارقام فارسی و عربی-هندی => ارقام لاتین. */
    private const DIGITS = [
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
    ];

    /** فاصله‌های غیرمعمول => فاصله‌ی ساده. نیم‌فاصله عمداً اینجا نیست (نگاه کنید به normalize). */
    private const SPACES = [
        "\u{00A0}" => ' ',   // NO-BREAK SPACE
        "\u{2000}" => ' ', "\u{2001}" => ' ', "\u{2002}" => ' ', "\u{2003}" => ' ',
        "\u{2004}" => ' ', "\u{2005}" => ' ', "\u{2006}" => ' ', "\u{2007}" => ' ',
        "\u{2008}" => ' ', "\u{2009}" => ' ', "\u{200A}" => ' ',
        "\u{202F}" => ' ', "\u{205F}" => ' ', "\u{3000}" => ' ',
        "\u{FEFF}" => '',    // ZERO WIDTH NO-BREAK SPACE (BOM)
    ];

    /** فقط حروف عربی را به فارسی تبدیل می‌کند. */
    public static function letters(string $text): string
    {
        return strtr($text, self::LETTERS);
    }

    /** فقط ارقام را به لاتین تبدیل می‌کند. */
    public static function digits(string $text): string
    {
        return strtr($text, self::DIGITS);
    }

    /**
     * یکسان‌سازی کامل: حروف + ارقام + فاصله‌ها، و حذف فاصله‌ی ابتدا/انتها.
     *
     * @param  bool  $collapseSpaces  چند فاصله‌ی پشت‌سرهم به یک فاصله تبدیل شود
     * @param  bool  $stripZwnj       نیم‌فاصله به فاصله تبدیل شود (برای جست‌وجو مفید است،
     *                                ولی برای ذخیره‌سازی نه - «می‌رود» نباید «می رود» شود)
     */
    public static function normalize(?string $text, bool $collapseSpaces = true, bool $stripZwnj = false): ?string
    {
        if ($text === null) {
            return null;
        }

        $text = strtr($text, self::LETTERS + self::DIGITS + self::SPACES);

        if ($stripZwnj) {
            $text = str_replace("\u{200C}", ' ', $text);
        }

        if ($collapseSpaces) {
            $text = preg_replace('/[ \t]+/u', ' ', $text) ?? $text;
        }

        return trim($text);
    }

    /**
     * آماده‌سازی یک عبارت برای جست‌وجو: علاوه بر یکسان‌سازی، نیم‌فاصله هم به فاصله تبدیل
     * می‌شود تا «سرپرست‌خانوار» و «سرپرست خانوار» یکدیگر را پیدا کنند.
     */
    public static function forSearch(?string $text): ?string
    {
        return self::normalize($text, collapseSpaces: true, stripZwnj: true);
    }
}
